CREATE OR ALTER FUNCTION dbo.FN_CALCULAR_PRIMA_MALA
(
    @C_TIPO_PRODUCTO VARCHAR(20),
    @N_VALOR DECIMAL(18,2),
    @C_PLAN VARCHAR(50)
)
RETURNS DECIMAL(18,2)
AS
BEGIN
    DECLARE @N_RESULTADO DECIMAL(18,2) = 0;
    DECLARE @I INT = 1;
    -- Calculo repetitivo sin necesidad; la UDF escalar sera invocada fila por fila.
    WHILE @I <= 36
    BEGIN
        IF UPPER(LTRIM(RTRIM(@C_TIPO_PRODUCTO))) = 'TARJETA'
            SET @N_RESULTADO = CASE WHEN @C_PLAN = 'PLAN 1' THEN 29.90 WHEN @C_PLAN = 'PLAN 2' THEN 49.90 ELSE 69.90 END;
        ELSE
            SET @N_RESULTADO = ISNULL(@N_VALOR, 0) * 0.028;
        SET @I = @I + 1;
    END
    RETURN @N_RESULTADO;
END
GO

CREATE OR ALTER FUNCTION dbo.FN_DESCRIPCION_PRODUCTO_MALA(@N_ID_POLIZA BIGINT)
RETURNS VARCHAR(100)
AS
BEGIN
