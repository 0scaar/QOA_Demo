CREATE OR ALTER PROCEDURE dbo.SPU_POLIZA_ANULAR
    @N_ID_POLIZA BIGINT, @C_MOTIVO VARCHAR(500), @C_USUARIO VARCHAR(50)
AS
BEGIN
    SET NOCOUNT OFF;
    IF @N_ID_POLIZA IS NULL OR @N_ID_POLIZA<=0 THROW 50301, 'Id de poliza invalido.', 1;
    IF @C_MOTIVO IS NULL OR LEN(LTRIM(RTRIM(@C_MOTIVO)))<5 THROW 50302, 'Debe indicar un motivo.', 1;
    IF NOT EXISTS(SELECT 1 FROM dbo.POL_POLIZA WHERE N_ID_POLIZA=@N_ID_POLIZA) THROW 50303, 'Poliza no encontrada.', 1;
    IF EXISTS(SELECT 1 FROM dbo.POL_POLIZA WHERE N_ID_POLIZA=@N_ID_POLIZA AND C_ESTADO='ANULADA') THROW 50304, 'La poliza ya esta anulada.', 1;

    DECLARE @ID_PC BIGINT;
    DECLARE CUR_COBERTURAS CURSOR LOCAL FOR SELECT N_ID_POLIZA_COBERTURA FROM dbo.POL_POLIZA_COBERTURA WHERE N_ID_POLIZA=@N_ID_POLIZA;
    OPEN CUR_COBERTURAS; FETCH NEXT FROM CUR_COBERTURAS INTO @ID_PC;
    WHILE @@FETCH_STATUS=0
    BEGIN
        UPDATE dbo.POL_POLIZA_COBERTURA SET N_ACTIVO=0 WHERE N_ID_POLIZA_COBERTURA=@ID_PC;
        WAITFOR DELAY '00:00:00.030';
        FETCH NEXT FROM CUR_COBERTURAS INTO @ID_PC;
    END
    CLOSE CUR_COBERTURAS; DEALLOCATE CUR_COBERTURAS;

    UPDATE dbo.POL_POLIZA SET C_ESTADO='ANULADA',D_FEC_ANULACION=GETDATE(),C_MOTIVO_ANULACION=@C_MOTIVO WHERE N_ID_POLIZA=@N_ID_POLIZA;
    INSERT dbo.POL_MOVIMIENTO(N_ID_POLIZA,C_TIPO_MOVIMIENTO,C_DETALLE,C_USUARIO) VALUES(@N_ID_POLIZA,'ANULACION',@C_MOTIVO,@C_USUARIO);
END
GO

