    SELECT @T = C_TIPO_PRODUCTO FROM dbo.POL_POLIZA WHERE N_ID_POLIZA = @N_ID_POLIZA;
    SET @R = CASE WHEN @T = 'TARJETA' THEN 'Proteccion de Tarjeta' ELSE 'Seguro Vehicular' END;
    RETURN @R;
END
